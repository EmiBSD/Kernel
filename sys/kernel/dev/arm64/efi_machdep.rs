    #[test]
    fn walk_descriptors() {
        // LZ's walk test: two descriptors 48 bytes apart (a descriptor size larger than the
        // structure), a size of 0 walking nothing.
        let mut map = [0u8; 96];
        map[0] = 5; // EfiRuntimeServicesCode
        map[8..16].copy_from_slice(&0x4000_0000u64.to_ne_bytes());
        map[24] = 2;
        map[32..40].copy_from_slice(&EFI_MEMORY_RUNTIME.to_ne_bytes());
        map[48] = 11; // EfiMemoryMappedIO
        let d: Vec<_> = descriptors(&map, 48).collect();
        assert_eq!(d.len(), 2);
        assert_eq!(d[0].Type, EfiRuntimeServicesCode);
        assert_eq!(d[0].PhysicalStart, 0x4000_0000);
        assert_eq!(d[0].NumberOfPages, 2);
        assert_eq!(d[0].Attribute, EFI_MEMORY_RUNTIME);
        assert_eq!(d[1].Type, 11);
        assert_eq!(descriptors(&map, 0).count(), 0);
        // A short last entry is not read.
        assert_eq!(descriptors(&map[..80], 40).count(), 2);
        assert_eq!(descriptors(&map[..79], 40).count(), 1);
    }

