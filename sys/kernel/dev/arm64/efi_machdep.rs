//! efi(4) on arm64 in the kernel: the UEFI runtime services, mapped into a pmap of their own,
//! and the time-of-day clock they provide (`GetTime`/`SetTime`). Under QEMU with EDK2 this is
//! the machine's clock: the firmware keeps the PL031 for itself and disables its device-tree
//! node, so plrtc(4) does not attach.
//!
//! Upstream: sys/arch/arm64/dev/efi_machdep.c @ 3ce1f3f79392
//! Upstream: sys/arch/arm64/include/efivar.h @ 3ce1f3f79392
//! LZ: sys/arch/arm64/dev/efi_machdep.rs@e8249449d905
//! LZ: sys/arch/arm64/include/efivar.rs@e8249449d905
//!
//! ## Deviations
//! - The memory map is `machdep.c`'s (`mmap`, `mmap_size`, `mmap_desc_size`, externs in the
//!   C too): `bsd`'s `initarm` hands its relocated copy to `hal` once, as a boot record
//!   (`hal::cpu::efi::set_boot_memory_map`), which `EfiRuntime::install` reads.
//!   The system table's address is read from `/chosen`, as the C's.
//! - Runtime calls are serialised (`hal::cpu::efi`'s lock) where the C shares one `efi_jmpbuf`
//!   between CPUs; a fault while reading the vendor string or a configuration entry ends that
//!   read (`EFAULT`, the loop stops) where the C would `longjmp` to whatever `efi_jmpbuf` held;
//!   every address read or called lies below the EFI pmap's limit.
//! - `efi_cd` (generated by `config(8)` in C, used by `dev/efi/efi.c`) is `ioconf.rs`'s stub.
//! - A memory map without a descriptor size maps nothing (the C would divide by zero); one
//!   whose runtime regions name kernel memory installs no runtime (a line says so; the C would
//!   map them).
//! - The vendor string's characters reach `printf` as `char`s, so a `CHAR16` whose low byte is
//!   0x80 or above prints two bytes (its UTF-8) where the C's `%c` prints one: the kernel's
//!   `printf(9)` path takes formatted text, and a byte path is `bsd`'s `subr_prf` to give
//!   (EDK II's vendor string is ASCII). Inherited: LZ prints the same way
//!   (`efi_machdep.rs`'s `char::from(c as u8)`).
//! - `efi.c` (`/dev/efi`, the variable services, the ESRT) and `smbios0 at efi?` are not
//!   ported (LZ's gaps): the `smbios` offer finds no driver, `sc_esrt` has no member.
//!
//! ## Redesign
//! - `efi_ca`/`efi_cd` -> [`EFI`], a [`DriverOps`] (decision 46) whose probe reads mainbus's
//!   [`FdtArgs`] back (`fa_name == "efi"`); `cfdata[]`'s row 8 names it (`Cfdata::native`) with
//!   a stub `Cfdriver` (`bsd`'s `conf/ioconf.rs`).
//! - `struct efi_softc` (LZ: `#[repr(C)]` with `Cell`s of raw pointers, `sc_pm`, `sc_rs`,
//!   `sc_esrt`, `sc_psw` and a `malloc`ed chip handle) -> the device's empty softc
//!   ([`EfiDev`]) and `hal::cpu::efi::EfiRuntime`, which owns the pmap, the table's address and
//!   the interrupt state of each call; the time-of-day chip is the static [`EFI_TODR`] (no
//!   handle to allocate: the C's `sc_todr` lives as long as the softc, which is never freed).
//! - `efi_enter`, `efi_leave`, `efi_enter_check`, `efi_fault` and `efi_jmpbuf` (LZ's assembly
//!   trampoline, `pcb_onfault`, `ci_curpm` and the interrupt state, 16 `unsafe` with the casts)
//!   -> `EfiRuntime`'s typed methods: [`EfiRuntime::reads`] for the vendor string and the
//!   configuration entries (one transaction for both, as the C's one `efi_enter`; each entry
//!   read whole and viewed with `hal::user::pod_from_bytes`), `get_time`, `set_time`.
//! - The system table is mapped through mainbus's bus (`FdtBus::map` of an [`Untyped`]
//!   block, write-back, `BUS_SPACE_MAP_LINEAR | BUS_SPACE_MAP_CACHEABLE`) and read by offsets
//!   (`offset_of!` of `sysdefs::dev::efi::EfiSystemTable`).
//! - `efi_map_runtime`'s pmap and descriptor walk are `EfiRuntime::install`'s (`hal`), which
//!   applies the C's policy to the memory map handed down and refuses kernel memory, so no
//!   caller can enter a page of its choosing into the pmap the runtime runs under.
//! - `efi_gettime`'s range checks and both conversions ([`efi_time_to_secs`],
//!   [`efi_time_of_secs`]) are pure, over `kernel::dev::clock_subr`.

