#[cfg(test)]
mod tests {
    use super::*;
    use std::format;
    use std::vec::Vec;

    #[test]
    fn the_version_line_and_the_early_return() {
        for (rev, line, usable) in [
            ((2 << 16) | 70, ": UEFI 2.7\n", true),
            ((2 << 16) | 31, ": UEFI 2.3.1\n", true),
            ((2 << 16) | 100, ": UEFI 2.10\n", true),
            ((2 << 16) | 9, ": UEFI 2.0.9\n", false),
            ((1 << 16) | 10, ": UEFI 1.1\n", false),
            ((3 << 16), ": UEFI 3.0\n", true),
        ] {
            let v = UefiVersion(rev);
            assert_eq!(format!("{v}"), line);
            assert_eq!(v.usable(), usable, "{line}");
        }
    }

    #[test]
    fn gettime_refuses_what_the_c_refuses() {
        let ok = EfiTime {
            Year: 2026,
            Month: 11,
            Day: 28,
            Hour: 23,
            Minute: 59,
            Second: 59,
            ..EfiTime::default()
        };
        assert_eq!(
            efi_time_to_secs(&ok),
            Ok(clock_ymdhms_to_secs(&ClockYmdhms {
                dt_year: 2026,
                dt_mon: 11,
                dt_day: 28,
                dt_hour: 23,
                dt_min: 59,
                dt_sec: 59,
                ..ClockYmdhms::default()
            }))
        );
        let bad = [
            EfiTime { Second: 60, ..ok },
            EfiTime { Minute: 60, ..ok },
            EfiTime { Hour: 24, ..ok },
            EfiTime { Day: 32, ..ok },
            EfiTime { Day: 0, ..ok },
            EfiTime { Month: 13, ..ok },
            EfiTime { Month: 0, ..ok },
            EfiTime { Year: 1969, ..ok },
        ];
        for t in bad {
            assert_eq!(efi_time_to_secs(&t), Err(Errno::EINVAL), "{t:?}");
        }
    }

    #[test]
    fn settime_hands_the_firmware_utc() {
        let t = efi_time_of_secs(1_795_838_400); // 2026-11-28 04:00:00 UTC
        assert_eq!((t.Year, t.Month, t.Day), (2026, 11, 28));
        assert_eq!((t.Hour, t.Minute, t.Second), (4, 0, 0));
        assert_eq!((t.Nanosecond, t.TimeZone, t.Daylight), (0, 0, 0));
        assert_eq!(efi_time_to_secs(&t), Ok(1_795_838_400));
    }

    #[test]
    fn the_configuration_table_names_the_acpi_and_smbios_tables() {
        let e = |g, t| EfiConfigurationTable {
            VendorGuid: g,
            VendorTable: t,
        };
        note_table(&e(EFI_ACPI_20_TABLE_GUID, 0x7000));
        note_table(&e(SMBIOS3_TABLE_GUID, 0x8000));
        note_table(&e(sysdefs::dev::efi::EFI_GLOBAL_VARIABLE, 0x9000));
        assert_eq!(EFI_ACPI_TABLE.load(Ordering::Relaxed), 0x7000);
        assert_eq!(EFI_SMBIOS_TABLE.load(Ordering::Relaxed), 0x8000);
        note_table(&e(SMBIOS_TABLE_GUID, 0xa000));
        assert_eq!(EFI_SMBIOS_TABLE.load(Ordering::Relaxed), 0xa000);
    }

    #[test]
    fn the_vendor_string_ends_at_its_nul_or_a_fault() {
        let rt = {
            let _g = crate::testutil::pages_install(4 << 20);
            crate::testutil::kernel_maps_install();
            match EfiRuntime::install(0x4000_0000) {
                Ok(rt) => rt,
                Err(_) => EfiRuntime::get().expect("installed"),
            }
        };
        hal::cpu::efi::fake::reset();
        let s: Vec<u8> = "EDK II\0"
            .encode_utf16()
            .flat_map(u16::to_ne_bytes)
            .collect();
        hal::cpu::efi::fake::map(0x1_0000, &s);
        let got: Vec<u16> = rt.reads(|r| vendor_chars(r, 0x1_0000).collect());
        assert_eq!(got, "EDK II".encode_utf16().collect::<Vec<_>>());
        // No NUL before the end of the mapping: the fault ends it, in the same transaction.
        hal::cpu::efi::fake::map(0x2_0000, &s[..6]);
        assert_eq!(rt.reads(|r| vendor_chars(r, 0x2_0000).count()), 3);
    }

    #[test]
    fn the_chip_is_the_last_resort() {
        assert_eq!(EFI_TODR.quality(), -1000);
    }
}
