/// `efi_acpi_table`: the ACPI 2.0 table's address, 0 if the firmware has none.
pub static EFI_ACPI_TABLE: AtomicU64 = AtomicU64::new(0);
/// `efi_smbios_table`: the SMBIOS (or SMBIOS 3) table's address, 0 if none.
pub static EFI_SMBIOS_TABLE: AtomicU64 = AtomicU64::new(0);

