/// The line `efi_attach` prints for the system table's revision: ` UEFI major.minor/10` and
/// `.minor%10` when not 0.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct UefiVersion(pub u32);

impl UefiVersion {
    /// Early implementations can be buggy: below 2.10 nothing more is done.
    pub fn usable(self) -> bool {
        let (major, minor) = (self.0 >> 16, self.0 & 0xffff);
        !(major < 2 || (major == 2 && minor < 10))
    }
}

impl core::fmt::Display for UefiVersion {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        let (major, minor) = (self.0 >> 16, self.0 & 0xffff);
        write!(f, ": UEFI {}.{}", major, minor / 10)?;
        if minor % 10 != 0 {
            write!(f, ".{}", minor % 10)?;
        }
        f.write_str("\n")
    }
}

/// `efi_match`: the `efi` pseudo-node mainbus offers when booted through UEFI.
pub fn efi_match(fa: &FdtArgs) -> i32 {
    i32::from(fa.name == b"efi")
}

impl DriverOps for EfiDriver {
    fn name(&self) -> &'static [u8] {
        b"efi"
    }
    fn class(&self) -> Devclass {
        DV_DULL
    }
    fn mode(&self) -> i32 {
        0
    }
    fn units(&self) -> &'static UnitTable {
        &EFI_UNITS
    }
    fn make_softc(&self, _id: &Ident<'_>) -> AnyArc {
        match MArc::new(M_DEVBUF, M_NOWAIT, EfiDev) {
            Some(sc) => MArc::erase(sc),
            None => kpanic(format_args!(
                "config_make_softc: allocation for device softc failed"
            )),
        }
    }
    fn probe(&self, _parent: Option<&DevRef>, _m: &Match, aux: &Aux<'_>) -> i32 {
        FdtArgs::of_aux(aux).map_or(0, efi_match)
    }
    fn attach(&self, _parent: Option<&DevRef>, dev: &DevRef, aux: &Aux<'_>) {
        let Some(fa) = FdtArgs::of_aux(aux) else {
            kpanic(format_args!("{}: not a device-tree node", dev.xname()));
        };
        efi_attach(dev, fa);
    }
}

/// A `u32` of the system table at `off`.
fn st32(st: &Mmio<Untyped>, off: usize) -> u32 {
    st.read_at::<u32>(off)
}

/// A `u64` of the system table at `off`.
fn st64(st: &Mmio<Untyped>, off: usize) -> u64 {
    st.read_at::<u64>(off)
}

/// `efi_attach`.
pub fn efi_attach(dev: &DevRef, fa: &FdtArgs) {
    let node = OF_finddevice(b"/chosen");
    kassert!(node != -1);

    let system_table = OF_getpropint64(node, b"openbsd,uefi-system-table", 0);
    kassert!(system_table != 0);

    let Ok(st) = fa.bus.map::<Untyped>(
        system_table,
        size_of::<EfiSystemTable>() as u64,
        DevCache::Cacheable,
    ) else {
        printf(format_args!(": can't map system table\n"));
        return;
    };

    let rs = st64(&st, offset_of!(EfiSystemTable, RuntimeServices));
    let revision = UefiVersion(st32(
        &st,
        offset_of!(EfiSystemTable, Hdr) + offset_of!(EfiTableHeader, Revision),
    ));
    printf(format_args!("{revision}"));

    // Early implementations can be buggy.
    if !revision.usable() {
        return;
    }

    let Some(rt) = efi_map_runtime(dev, rs) else {
        return;
    };

    // Activate our pmap such that we can access the FirmwareVendor and ConfigurationTable
    // fields.
    let vendor = st64(&st, offset_of!(EfiSystemTable, FirmwareVendor));
    let fwrev = st32(&st, offset_of!(EfiSystemTable, FirmwareRevision));
    let n = st64(&st, offset_of!(EfiSystemTable, NumberOfTableEntries));
    let ct = st64(&st, offset_of!(EfiSystemTable, ConfigurationTable));
    rt.reads(|r| {
        if vendor != 0 {
            printf(format_args!("{}: ", dev.xname()));
            for c in vendor_chars(r, vendor) {
                printf(format_args!("{}", char::from(c as u8)));
            }
            printf(format_args!(" rev 0x{fwrev:x}\n"));
        }
        scan_configuration(r, ct, n);
    });

    let smbios = EFI_SMBIOS_TABLE.load(Ordering::Relaxed);
    if smbios != 0 {
        let sa = FdtArgs::named_reg(
            b"smbios",
            &fa.bus,
            FdtReg {
                addr: smbios,
                size: 0,
            },
        );
        let _ = config_found(dev, &Aux::Typed(&sa), None);
    }

    if !matches!(rt.get_time(), Ok((EFI_SUCCESS, _))) {
        return;
    }

    // EDK II implementations provide an implementation of GetTime() that returns a fixed
    // compiled-in time on hardware without a (supported) RTC. So only use this interface as a
    // last resort.
    todr_attach(&EFI_TODR);
}

/// The vendor string's characters at `vendor`, up to its NUL: one `CHAR16` a read; a fault
/// ends the string.
fn vendor_chars<'a>(r: &'a EfiReads<'_>, vendor: u64) -> impl Iterator<Item = u16> + 'a {
    (0u64..)
        .map(move |i| {
            let mut c = [0u8; 2];
            let va = vendor.checked_add(i * 2)?;
            r.read(va, &mut c).ok()?;
            Some(u16::from_ne_bytes(c))
        })
        .map_while(|c| c.filter(|&c| c != 0))
}

/// `efi_attach`'s configuration table walk: `efi_acpi_table` and `efi_smbios_table` from the
/// GUIDs of the `n` entries at `ct`; a fault ends the walk.
fn scan_configuration(r: &EfiReads<'_>, ct: u64, n: u64) {
    let len = size_of::<EfiConfigurationTable>();
    for i in 0..n {
        let mut b = [0u8; size_of::<EfiConfigurationTable>()];
        let Some(va) = i.checked_mul(len as u64).and_then(|o| ct.checked_add(o)) else {
            break;
        };
        if r.read(va, &mut b).is_err() {
            break;
        }
        let Some(e) = pod_from_bytes::<EfiConfigurationTable>(&b) else {
            break;
        };
        note_table(&e);
    }
}

/// One configuration entry's GUID checked against the three tables efi(4) records.
fn note_table(e: &EfiConfigurationTable) {
    if e.VendorGuid == EFI_ACPI_20_TABLE_GUID {
        EFI_ACPI_TABLE.store(e.VendorTable, Ordering::Relaxed);
    }
    if e.VendorGuid == SMBIOS_TABLE_GUID {
        EFI_SMBIOS_TABLE.store(e.VendorTable, Ordering::Relaxed);
    }
    if e.VendorGuid == SMBIOS3_TABLE_GUID {
        EFI_SMBIOS_TABLE.store(e.VendorTable, Ordering::Relaxed);
    }
}

/// `efi_map_runtime`: we don't really want some random executable non-OpenBSD code lying
/// around in kernel space. So create a separate pmap and only activate it when we call
/// runtime services. `hal::cpu::efi::EfiRuntime::install` makes the pmap and enters the
/// runtime regions of the boot record's memory map (`initarm` hands it to `hal`), with the
/// C's policy, and keeps the table at `rs`; `None` (the line printed) when the map names
/// kernel memory.
pub fn efi_map_runtime(dev: &DevRef, rs: u64) -> Option<&'static EfiRuntime> {
    match EfiRuntime::install(rs) {
        Ok(rt) => Some(rt),
        Err(Errno::EBUSY) => kpanic(format_args!(
            "efi_map_runtime: the runtime services are mapped already"
        )),
        Err(Errno::EINVAL) => {
            printf(format_args!(
                "{}: the memory map's runtime regions name kernel memory: not mapped\n",
                dev.xname()
            ));
            None
        }
        Err(_) => kpanic(format_args!("efi_map_runtime: no pmap")),
    }
}

/// `efi_gettime`'s conversion: the firmware's time as POSIX seconds, `EINVAL` when a field
/// is out of range.
pub fn efi_time_to_secs(time: &EfiTime) -> Result<i64, Errno> {
    let dt = ClockYmdhms {
        dt_year: time.Year,
        dt_mon: time.Month,
        dt_day: time.Day,
        dt_hour: time.Hour,
        dt_min: time.Minute,
        dt_sec: time.Second,
        ..ClockYmdhms::default()
    };

    if dt.dt_sec > 59
        || dt.dt_min > 59
        || dt.dt_hour > 23
        || dt.dt_day > 31
        || dt.dt_day == 0
        || dt.dt_mon > 12
        || dt.dt_mon == 0
        || i32::from(dt.dt_year) < POSIX_BASE_YEAR
    {
        return Err(Errno::EINVAL);
    }

    Ok(clock_ymdhms_to_secs(&dt))
}

/// `efi_settime`'s conversion: the POSIX seconds `secs` as the firmware's time, UTC.
pub fn efi_time_of_secs(secs: i64) -> EfiTime {
    let dt = clock_secs_to_ymdhms(secs);

    EfiTime {
        Year: dt.dt_year,
        Month: dt.dt_mon,
        Day: dt.dt_day,
        Hour: dt.dt_hour,
        Minute: dt.dt_min,
        Second: dt.dt_sec,
        Nanosecond: 0,
        TimeZone: 0,
        Daylight: 0,
        ..EfiTime::default()
    }
}

/// `efi_gettime`.
pub fn efi_gettime() -> Result<Timeval, Errno> {
    let rt = EfiRuntime::get().ok_or(Errno::ENXIO)?;
    let (status, time) = rt.get_time()?;
    if status != EFI_SUCCESS {
        return Err(Errno::EIO);
    }

    Ok(Timeval {
        tv_sec: efi_time_to_secs(&time)?,
        tv_usec: 0,
    })
}

/// `efi_settime`.
pub fn efi_settime(tv: &Timeval) -> Result<(), Errno> {
    let rt = EfiRuntime::get().ok_or(Errno::ENXIO)?;
    let status = rt.set_time(&efi_time_of_secs(tv.tv_sec))?;
    if status != EFI_SUCCESS {
        return Err(Errno::EIO);
    }
    Ok(())
}

impl Todr for EfiTodr {
    fn quality(&self) -> i32 {
        -1000
    }

    fn gettime(&self) -> Result<Timeval, Errno> {
        efi_gettime()
    }

    fn settime(&self, tv: &Timeval) -> Result<(), Errno> {
        efi_settime(tv)
    }
}
